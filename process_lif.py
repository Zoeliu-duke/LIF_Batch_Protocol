def tissue_mask(stack, um_px):
    blur = filters.gaussian(stack.sum(0), sigma=8 if low_mag(um_px) else 3)
    return morphology.remove_small_objects(blur > 0.35 * filters.threshold_otsu(blur), max_size=5000)

CONTROL_WORDS = [w for w in [CONTROL_TAG] + [c.get("control", "") for c in CHANNELS] if w]

def is_control(n):
    """Any kind of control sample (general CONTROL_TAG or a channel's negative control)."""
    return any(w in n for w in CONTROL_WORDS)

def compute_ranges(stacks, g):
    """(min, max) per channel for group g. stacks: name -> denoised C,Y,X."""
    std = stacks[STANDARD[g]]; um_px = data[(g, STANDARD[g])]["um_px"]
    m_std = tissue_mask(std, um_px)
    region_px, control_px = {}, {}
    need_region = any(isinstance(r, tuple) and r[0] == "region" for c in CHANNELS for r in rules(c))
    need_control = any(isinstance(r, tuple) and r[0] == "control" for c in CHANNELS for r in rules(c))
    for n, st in stacks.items():
        m = tissue_mask(st, um_px)
        if need_region and not is_control(n):
            ref = sum(st[c] / max(np.median(st[c][m]), 1e-6) for c in REGION)
            ref = filters.gaussian(ref, 20 if low_mag(um_px) else 25)
            bg = m & (ref < np.percentile(ref[m], 100 * LOW_REGION["fraction"]))
            for c in range(NCH): region_px.setdefault(c, []).append(st[c][bg])
        if need_control:
            for c in range(NCH):                              # each channel: its own controls
                w = CHANNELS[c].get("control", "")
                if w and w in n: control_px.setdefault(c, []).append(st[c][m])
    out = []
    for c in range(NCH):
        vals = []
        for r in rules(CHANNELS[c]):
            if isinstance(r, (int, float)): vals.append(float(r))
            elif r[0] == "pct": vals.append(float(np.percentile(std[c][m_std], r[1])))
            elif r[0] == "region": vals.append(float(np.percentile(np.concatenate(region_px[c]), r[1])))
            elif r[0] == "control":
                w = CHANNELS[c].get("control", "")
                if not w: fail(f"{CH[c]} uses ('control', ..) but has no negative control. Add control=\"word\" "
                               f"to that channel, or use a ('pct', ..) / ('region', ..) rule instead.")
                if c not in control_px: fail(f"{CH[c]}: no processed sample in this group contains its control word '{w}'")
                vals.append(float(np.percentile(np.concatenate(control_px[c]), r[1])))
            else: fail(f"unknown background rule {r} for {CH[c]}")
        lo = max(vals)
        hi = float(max(np.percentile(std[c][m_std], HI_PCT), lo + 5)) * CHANNELS[c]["brightness"]
        out.append((lo, hi))
    return out

