def best_z(im):
    """Sharpest plane: max Laplacian variance of blurred focus channels (not divided by
    brightness, so near-empty planes above/below the tissue do not win)."""
    score = []
    for z in range(im.dims.z):
        a = sum(filters.gaussian(np.asarray(im.get_frame(z=z, c=c), np.float32), 1.5,
                                 preserve_range=True) for c in FOCUS)
        score.append(filters.laplace(a).var())
    return int(np.argmax(score))

def denoise(stack):
    out = []
    for ch in stack:
        if DENOISE.get("median", 1) > 1: ch = ndi.median_filter(ch, DENOISE["median"])
        if DENOISE.get("gaussian", 0) > 0: ch = filters.gaussian(ch, DENOISE["gaussian"], preserve_range=True)
        out.append(ch)
    return np.stack(out).astype(np.float32)

# ---- tile stitching (like Fiji Grid/Collection stitching with "compute overlap") -----------
def _ncc(a, b):
    a = a - a.mean(); b = b - b.mean()
    return float((a * b).sum() / np.sqrt((a * a).sum() * (b * b).sum() + 1e-9))

def _pair_offset(t, u, horizontal, T):
    """Best (score, overlap, drift) placing u right of (horizontal) or below t."""
    def score(o, d):
        if horizontal:
            a = t[max(d, 0):T + min(d, 0), T - o:]; b = u[max(-d, 0):T + min(-d, 0), :o]
            return _ncc(a[20:-20], b[20:-20])
        a = t[T - o:, max(d, 0):T + min(d, 0)]; b = u[:o, max(-d, 0):T + min(-d, 0)]
        return _ncc(a[:, 20:-20], b[:, 20:-20])
    lo, hi = (int(f * T) for f in STITCH["overlap_search"])
    D = STITCH["drift_search"]
    _, o0, d0 = max((score(o, d), o, d) for o in range(lo, hi + 1, 2) for d in range(-D, D + 1, 2))
    return max((score(o, d), o, d) for o in range(o0 - 2, o0 + 3) for d in range(d0 - 2, d0 + 3))

def tile_grid(im):
    return [(int(p[0]), int(p[1])) for p in im.mosaic_position]   # (row, col)

def place(grid, T, oLR, dLR, oTB, dTB):
    """Tile top-left corners for a regular grid with the given overlaps and sideways drifts (px)."""
    pos = {rc: (rc[0] * (T - oTB) + rc[1] * dLR, rc[1] * (T - oLR) + rc[0] * dTB) for rc in grid}
    y0 = min(p[0] for p in pos.values()); x0 = min(p[1] for p in pos.values())
    return {rc: (int(p[0] - y0), int(p[1] - x0)) for rc, p in pos.items()}

def offsets_from(choice, T):
    """(overlap_LR, drift_LR, overlap_TB, drift_TB) in pixels for "fixed" or your numbers (dict)."""
    if choice == "fixed":
        ov = round(STITCH["overlap_start"] * T); return (ov, 0, ov, 0)
    o = choice.get("overlap", 100 * STITCH["overlap_start"])
    return (round(choice.get("overlap_LR", o) / 100 * T), int(choice.get("drift_LR", 0)),
            round(choice.get("overlap_TB", o) / 100 * T), int(choice.get("drift_TB", 0)))

class StitchedScan:
    """Stitches a Leica tile scan; behaves like a readlif image (dims, get_frame, scale).
    offsets None = measure them here ("registered"); otherwise (oLR, dLR, oTB, dTB) in pixels."""
    def __init__(self, im, offsets=None, how="registered"):
        self.im, T = im, im.dims.x
        self.T = T
        grid = tile_grid(im)
        pair_min = None
        if offsets is None:
            feat = {}
            for m, rc in enumerate(grid):
                t = sum(np.asarray(im.get_frame(z=z, c=c, m=m), np.float32)
                        for z in range(im.dims.z) for c in FOCUS)
                t = filters.gaussian(t, 2)
                feat[rc] = t - filters.gaussian(t, 25)         # remove illumination pattern
            lr, tb = [], []
            for (r, c), t in feat.items():
                if (r, c + 1) in feat: lr.append(_pair_offset(t, feat[(r, c + 1)], True, T))
                if (r + 1, c) in feat: tb.append(_pair_offset(t, feat[(r + 1, c)], False, T))
            med = lambda L, i, default: int(np.median([x[i] for x in L])) if L else default
            ov0 = round(STITCH["overlap_start"] * T)
            offsets = (med(lr, 1, ov0), med(lr, 2, 0), med(tb, 1, ov0), med(tb, 2, 0))
            pair_min = round(min(x[0] for x in lr + tb), 3) if lr + tb else None
        oLR, dLR, oTB, dTB = offsets
        self.fit = {"method": how, "overlap_LR_pct": round(100 * oLR / T, 2), "overlap_TB_pct": round(100 * oTB / T, 2),
                    "drift_LR_px": dLR, "drift_TB_px": dTB, "pair_ncc_min": pair_min}
        P = place(grid, T, oLR, dLR, oTB, dTB)
        self.pos = [P[rc] for rc in grid]
        H = max(p[0] for p in self.pos) + T; W = max(p[1] for p in self.pos) + T
        ramp = np.minimum(np.arange(T) + 1, T - np.arange(T)).astype(np.float32)
        self.w = np.outer(ramp, ramp)                           # linear blending weights
        self.wsum = np.zeros((H, W), np.float32)
        for y, x in self.pos: self.wsum[y:y + T, x:x + T] += self.w
        self.dims = type(im.dims)(x=W, y=H, z=im.dims.z, t=1, m=1)
        self.scale, self.info, self.bit_depth = im.scale, im.info, im.bit_depth

    def get_frame(self, z=0, c=0, **_):
        out = np.zeros(self.wsum.shape, np.float32); T = self.T
        for m, (y, x) in enumerate(self.pos):
            out[y:y + T, x:x + T] += np.asarray(self.im.get_frame(z=z, c=c, m=m), np.float32) * self.w
        return out / np.maximum(self.wsum, 1e-9)

# ---- comparing stitching options: seam scores (how well overlapping tiles agree) -------------
reg_cache, tile_cache, layout_cache, score_cache = {}, {}, {}, {}

def _feat(a):
    a = filters.gaussian(a, 2); return a - filters.gaussian(a, 25)

def seam_tiles(name, im):
    if name not in tile_cache:
        z = im.dims.z // 2
        tile_cache[name] = {rc: _feat(sum(np.asarray(im.get_frame(z=z, c=c, m=m), float) for c in FOCUS))
                            for m, rc in enumerate(tile_grid(im))}
    return tile_cache[name]

def seam_score(tiles, pos, T):
    """Mean and worst normalized cross-correlation of all overlapping tile pairs (1 = perfect)."""
    sc = []; keys = list(pos)
    for i, a in enumerate(keys):
        for b in keys[i + 1:]:
            (ya, xa), (yb, xb) = pos[a], pos[b]
            y0, y1 = max(ya, yb), min(ya, yb) + T; x0, x1 = max(xa, xb), min(xa, xb) + T
            if y1 - y0 < 40 or x1 - x0 < 40: continue
            A = tiles[a][y0 - ya:y1 - ya, x0 - xa:x1 - xa]; B = tiles[b][y0 - yb:y1 - yb, x0 - xb:x1 - xb]
            sc.append(_ncc(A[10:-10, 10:-10], B[10:-10, 10:-10]))
    return (round(float(np.mean(sc)), 3), round(float(np.min(sc)), 3)) if sc else (np.nan, np.nan)

def leica_positions(mer, tiles, T):
    """Where each raw tile sits in Leica's merged image."""
    from skimage.feature import match_template
    z = mer.dims.z // 2
    M = _feat(sum(np.asarray(mer.get_frame(z=z, c=c), float) for c in FOCUS)); pos = {}
    ov = round(STITCH["overlap_start"] * T)
    for (r, c), t in tiles.items():
        gy, gx = r * (T - ov), c * (T - ov); y0, x0 = max(gy - 150, 0), max(gx - 150, 0)
        res = match_template(M[y0:gy + T + 150, x0:gx + T + 150], t[100:-100, 100:-100])
        yy, xx = np.unravel_index(np.argmax(res), res.shape); pos[(r, c)] = (y0 + yy - 100, x0 + xx - 100)
    return pos

def stitch_scores(name, im, mer_i):
    """Seam scores of Leica's merge, the fixed overlap and the registered stitch of one tile scan."""
    if name not in score_cache:
        T, grid, tiles = im.dims.x, tile_grid(im), seam_tiles(name, im)
        if name not in reg_cache: reg_cache[name] = StitchedScan(im)
        lay = {"fixed": place(grid, T, *offsets_from("fixed", T)), "registered": dict(zip(grid, reg_cache[name].pos))}
        if mer_i is not None: lay = {"leica": leica_positions(lif.get_image(mer_i), tiles, T), **lay}
        layout_cache[name] = lay
        score_cache[name] = {k: seam_score(tiles, p, T) for k, p in lay.items()}
    return score_cache[name]

