    lines = [f"groups = {arr(q(g) for g in GROUPS)};", f'barPos = "{SCALEBAR_POS}";',
             f"bars = {arr(str(bar_um(g, data[(g, STANDARD[g])]['um_px'], data[(g, STANDARD[g])]['stack'].shape[2])) for g in GROUPS)};",
             f"names = {arr(q(c) for c in CH)};",
             f"luts = {arr(q(FIJI_LUT[c['color']]) for c in CHANNELS)};",
             f'focus = "{",".join(str(i + 1) for i in FOCUS)}";']
    for mode in ("single", "avg", "max"):
        lines.append(f"{mode}_min = {arr(num(pr[(g, mode)][c][0]) for g in GROUPS for c in range(NCH))};")
        lines.append(f"{mode}_max = {arr(num(pr[(g, mode)][c][1]) for g in GROUPS for c in range(NCH))};")
