def composite(stack, rng, chans=None, recolor=None):
    rgb = np.zeros(stack.shape[1:] + (3,), np.float32)
    for c in (range(NCH) if chans is None else chans):
        col = np.array(COLORS[(recolor or {}).get(c, CHANNELS[c]["color"])])
        lo, hi = rng[c]
        rgb += np.clip((stack[c] - lo) / (hi - lo), 0, 1)[..., None] * col
    return np.clip(rgb, 0, 1)

def bar_um(g, um_px, width_px):
    if g in SCALEBAR_UM: return SCALEBAR_UM[g]
    target = um_px * width_px / 8
    nice = [1, 2, 5, 10, 20, 50, 100, 200, 500, 1000, 2000]
    return min(nice, key=lambda v: abs(np.log(v / target)))

def scalebar(ax, um_per_px, width_px, um, pos=None):
    """White bar of `um` micrometres (length = um / um_per_px image pixels) with its label,
    at SCALEBAR_POS: lower/upper + left/right, or center."""
    pos = pos or SCALEBAR_POS
    L = um / um_per_px; h = width_px * 0.012
    height_px = ax.get_ylim()[0] + 0.5                       # imshow: y runs from -0.5 to H-0.5
    margin = width_px * 0.04
    x0 = {"left": margin, "right": width_px - margin - L}.get(pos.split()[-1], (width_px - L) / 2)
    if pos.startswith("upper"):
        y0 = h * 2                                          # bar near the top, label under it
        ax.text(x0 + L / 2, y0 + h * 2, f"{um} µm", color="white", ha="center", va="top", fontsize=9)
    else:
        y0 = height_px - h * 3 if pos.startswith("lower") else (height_px - h) / 2
        ax.text(x0 + L / 2, y0 - h, f"{um} µm", color="white", ha="center", va="bottom", fontsize=9)
    ax.add_patch(plt.Rectangle((x0, y0), L, h, color="white"))

